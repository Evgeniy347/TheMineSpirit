package com.theminespirit.core.ui;

/**
 * Группа плитки на экране доски, в порядке показа: завершённые, активные (выданы духу) и доступные
 * (ресурсов хватает, зависимости выполнены). Задания, которые не удалось завершить (не хватает ресурсов,
 * ждут зависимостей, заблокированы, провалены или сняты), лежат в колонке завершённых и помечены
 * {@link BoardTile#unfinished()}.
 */
public enum BoardTileGroup {
    DONE,
    ACTIVE,
    AVAILABLE
}
