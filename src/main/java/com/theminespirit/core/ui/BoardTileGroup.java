package com.theminespirit.core.ui;

/**
 * Группа плитки на экране доски, в порядке показа: завершённые, активные (выданы духу), доступные
 * (ресурсов хватает, зависимости выполнены) и недоступные (не хватает ресурсов, ждут зависимостей,
 * заблокированы, провалены или сняты).
 */
public enum BoardTileGroup {
    DONE,
    ACTIVE,
    AVAILABLE,
    UNAVAILABLE
}
