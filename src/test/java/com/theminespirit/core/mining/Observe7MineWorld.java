package com.theminespirit.core.mining;

final class Observe7MineWorld {
    private static final int X0 = -191;
    private static final int Y0 = 58;
    private static final int Z0 = -520;
    private static final int SIZE_X = 5;
    private static final int SIZE_Z = 18;
    private static final String[] LAYERS = {
        "######GG##GGGG#GGGG#GGGGG#GGGG#GGGG##GGG##GGG###GG#################.####.####.############",
        "######GG##GGGG#GGGGGGGGGGGGGGG#GGGG#GGGG##GGG##GGG####G#######.####.####.#################",
        "###########GG###GGG#GGGGG#GGGG#GGGG##GGG##GGG##GGG####G##.####.####.######################",
        "######################G####GG###GG####GG###GG#######.####.####.###########################",
        "###############################################.####.####.################################",
        "##########################################.####.####.#####################################",
        "##################################.##.#.GG.#.##.######.###################################",
        "################################.####.####.###############################################",
        "##.##...##..###############.####.####.####################################################",
        "##..#....##..#...##..#.####.##.#.##..###########################################.#####..#.",
        "##...#...##.#.###.####.####.###....#..##...#....###..#.#..##...#....##...#.#..#.#..#.#....",
        "...........#.#..#.#..#.#..................................................................",
        "...........#.#..#.#.......................................................................",
        "...........#.#............................................................................",
        "..........................................................................................",
        "..........................................................................................",
    };

    private Observe7MineWorld() {}

    static CellWorld build() {
        CellWorld world = new CellWorld();
        for (int y = 0; y < LAYERS.length; y++) {
            String layer = LAYERS[y];
            for (int z = 0; z < SIZE_Z; z++) {
                for (int x = 0; x < SIZE_X; x++) {
                    char cell = layer.charAt(z * SIZE_X + x);
                    if (cell == '#') {
                        world.set(X0 + x, Y0 + y, Z0 + z, Cell.SOLID);
                    } else if (cell == '~') {
                        world.set(X0 + x, Y0 + y, Z0 + z, Cell.WATER);
                    } else if (cell == 'L') {
                        world.set(X0 + x, Y0 + y, Z0 + z, Cell.LAVA);
                    } else if (cell == 'G') {
                        world.set(X0 + x, Y0 + y, Z0 + z, Cell.FALLING);
                    }
                }
            }
        }
        return world;
    }
}
